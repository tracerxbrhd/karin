//! Bounded speculative reads exercise the real exact-content permission policy.
use super::*;
use crate::audio_cache::{
    licensed::{LicensedResource, LicensedResourceAuthority},
    test_support::{SyntheticAudio, account},
};
use std::{
    sync::{Condvar, mpsc},
    thread,
    time::Instant,
};

struct BlockingPermission {
    rights: LicensedResourceAuthority,
    hold_next: AtomicBool,
    entered: mpsc::Sender<()>,
    release: Arc<(Mutex<bool>, Condvar)>,
}
impl StorageAuthority for BlockingPermission {
    fn authorize(&self, identity: &ResourceIdentity) -> Result<StorageGrant> {
        if self.hold_next.swap(false, Ordering::AcqRel) {
            self.entered.send(()).unwrap();
            let released = self.release.0.lock().unwrap();
            let (released, _) = self
                .release
                .1
                .wait_timeout_while(released, Duration::from_secs(5), |released| !*released)
                .unwrap();
            assert!(*released, "bounded permission lookup was not released");
        }
        self.rights.authorize(identity)
    }
    fn check(&self, grant: &StorageGrant) -> Result<()> {
        self.rights.check(grant)
    }
}
struct Release(Arc<(Mutex<bool>, Condvar)>);
impl Drop for Release {
    fn drop(&mut self) {
        *self.0.0.lock().unwrap() = true;
        self.0.1.notify_all();
    }
}

struct Fixture {
    _directory: Arc<Sandbox>,
    permission: Arc<BlockingPermission>,
    entered: mpsc::Receiver<()>,
    cache: AudioCache,
    lease: Lease,
    audio: SyntheticAudio,
}
impl Fixture {
    fn new() -> Self {
        let directory = Sandbox::create(&std::env::temp_dir()).unwrap();
        let audio = SyntheticAudio::tone(400).unwrap();
        // These original generated bytes have an explicit creator CC0-1.0
        // dedication. The production policy authorizes their exact digest only.
        let resource = LicensedResource::cc0(
            &account(1),
            101u64.into(),
            digest(&SHA256, &audio.0).as_ref().try_into().unwrap(),
            audio.0.len() as u64,
        )
        .unwrap();
        let (entered, observed) = mpsc::channel();
        let permission = Arc::new(BlockingPermission {
            rights: LicensedResourceAuthority::new(vec![resource]).unwrap(),
            hold_next: AtomicBool::new(false),
            entered,
            release: Arc::new((Mutex::new(false), Condvar::new())),
        });
        let cache = AudioCache::open(
            directory.path.join("audio"),
            Arc::new(OnlineStreamAuthority::with_storage_permission(
                permission.clone(),
            )),
            CachePolicy::default(),
        )
        .unwrap();
        let lease = cache.bind(Some(account(1))).unwrap().unwrap();
        Self {
            _directory: directory,
            permission,
            entered: observed,
            cache,
            lease,
            audio,
        }
    }
    fn begin(&self, lease: &Lease) -> OnlineCheck {
        self.cache.begin_online_check(lease, 101u64.into()).unwrap()
    }
    fn existing_record(&self) {
        self.cache
            .observe_verified_online(&self.lease, self.begin(&self.lease))
            .unwrap();
        self.cache
            .put_reader(
                self.cache.begin(&self.lease, 101u64).unwrap(),
                self.audio.0.as_slice(),
            )
            .unwrap();
    }
    fn hold_next(&self) -> Release {
        *self.permission.release.0.lock().unwrap() = false;
        self.permission.hold_next.store(true, Ordering::Release);
        Release(self.permission.release.clone())
    }
    fn wait_idle(&self) {
        let deadline = Instant::now() + Duration::from_secs(2);
        while self.cache.0.lookup_running.load(Ordering::Acquire) {
            assert!(
                Instant::now() < deadline,
                "cache worker did not release its one slot"
            );
            thread::yield_now();
        }
    }
    fn prepared(&self, lease: &Lease) -> PreparedSelection {
        let lookup = self.cache.lookup(lease.clone(), self.begin(lease)).unwrap();
        let prepared = lookup
            .result
            .recv_timeout(Duration::from_secs(2))
            .unwrap()
            .unwrap();
        drop(lookup);
        prepared
    }
}

#[test]
fn slow_permission_lookup_never_waits_on_selection_or_accumulates_workers() {
    let f = Fixture::new();
    let released = f.hold_next();
    let lookup = f.cache.lookup(f.lease.clone(), f.begin(&f.lease)).unwrap();
    f.entered.recv_timeout(Duration::from_secs(2)).unwrap();
    assert!(f.cache.lookup(f.lease.clone(), f.begin(&f.lease)).is_none());
    let (done, received) = mpsc::channel();
    let selection = thread::spawn(move || done.send(lookup.ready().is_none()).unwrap());
    assert!(
        received
            .recv_timeout(Duration::from_secs(1))
            .expect("selection must finish while permission I/O remains blocked",)
    );
    selection.join().unwrap();
    assert!(f.cache.0.lookup_running.load(Ordering::Acquire));
    assert!(matches!(
        f.cache.get(&f.lease, 101u64),
        Err(CacheError::NoGrant)
    ));
    drop(released);
    f.wait_idle();
    assert!(matches!(
        f.cache.get(&f.lease, 101u64),
        Err(CacheError::NoGrant)
    ));
    assert_eq!(f.cache.stats().unwrap().entries, 0);
    assert!(f.cache.0.state.lock().unwrap().pending.is_empty());
}

#[test]
fn verified_local_candidate_needs_a_current_fresh_admission_before_becoming_playable() {
    let f = Fixture::new();
    f.existing_record();
    let old_hit = f.cache.get(&f.lease, 101u64).unwrap().unwrap();
    let candidate = f.prepared(&f.lease);
    assert!(candidate.file.is_some());
    assert!(matches!(
        f.cache.get(&f.lease, 101u64),
        Err(CacheError::NoGrant)
    ));
    assert!(matches!(old_hit.admit_file(), Err(CacheError::Revoked)));
    assert!(matches!(
        candidate.admit(|| false),
        Err(CacheError::Cancelled)
    ));
    f.wait_idle();
    assert!(matches!(
        f.cache.get(&f.lease, 101u64),
        Err(CacheError::NoGrant)
    ));
    assert_eq!(f.cache.stats().unwrap().entries, 1);

    let candidate = f.prepared(&f.lease);
    assert!(matches!(
        f.cache.get(&f.lease, 101u64),
        Err(CacheError::NoGrant)
    ));
    let hit = candidate.admit(|| true).unwrap().unwrap();
    assert_eq!(&*hit.admit().unwrap(), &f.audio.0);
    f.wait_idle();
    assert!(f.cache.get(&f.lease, 101u64).unwrap().is_some());
}

#[test]
fn delayed_unopened_local_hit_expires_but_an_already_pinned_file_survives() {
    use std::os::unix::fs::FileExt;

    let f = Fixture::new();
    f.existing_record();
    let mut candidate = f.prepared(&f.lease);
    candidate.admission_deadline = Some(Instant::now() + Duration::from_millis(40));
    let hit = candidate.admit(|| true).unwrap().unwrap();
    let active = hit.admit_file().unwrap();
    thread::sleep(Duration::from_millis(60));
    assert!(matches!(hit.admit_file(), Err(CacheError::Expired)));
    f.wait_idle();
    f.cache.clear().unwrap();
    let mut bytes = vec![0; f.audio.0.len()];
    active.read_exact_at(&mut bytes, 0).unwrap();
    assert_eq!(bytes, f.audio.0);
}

#[test]
fn bounded_offer_lookup_honors_cancellation_without_waiting_for_permission_io() {
    let f = Fixture::new();
    let released = f.hold_next();
    let lookup = f.cache.lookup(f.lease.clone(), f.begin(&f.lease)).unwrap();
    f.entered.recv_timeout(Duration::from_secs(2)).unwrap();
    let began = Instant::now();
    assert!(lookup.wait(|| false).is_none());
    assert!(began.elapsed() < Duration::from_millis(100));
    assert!(f.cache.0.lookup_running.load(Ordering::Acquire));
    drop(released);
    f.wait_idle();
}

#[test]
fn lease_replacement_retires_inflight_lookup_without_destroying_healthy_bytes() {
    let f = Fixture::new();
    f.existing_record();
    let old_hit = f.cache.get(&f.lease, 101u64).unwrap().unwrap();
    let released = f.hold_next();
    let lookup = f.cache.lookup(f.lease.clone(), f.begin(&f.lease)).unwrap();
    f.entered.recv_timeout(Duration::from_secs(2)).unwrap();
    let replacement = f.cache.bind(Some(account(1))).unwrap().unwrap();
    assert!(matches!(old_hit.admit_file(), Err(CacheError::Cancelled)));
    drop(released);
    assert!(matches!(
        lookup.result.recv_timeout(Duration::from_secs(2)).unwrap(),
        Err(CacheError::Cancelled),
    ));
    drop(lookup);
    f.wait_idle();
    assert_eq!(f.cache.stats().unwrap().entries, 1);
    assert!(matches!(
        f.cache.get(&replacement, 101u64),
        Err(CacheError::NoGrant)
    ));
    let hit = f.prepared(&replacement).admit(|| true).unwrap().unwrap();
    assert_eq!(&*hit.admit().unwrap(), &f.audio.0);
    f.wait_idle();
}

#[test]
fn fresh_private_http_source_admission_is_memory_only_when_disk_lookup_is_not_ready() {
    let directory = Sandbox::create(&std::env::temp_dir()).unwrap();
    let cache = AudioCache::open(
        directory.path.join("audio"),
        Arc::new(OnlineStreamAuthority::with_storage_permission(Arc::new(
            PrivateHttpCachePolicy,
        ))),
        CachePolicy::default(),
    )
    .unwrap();
    let lease = cache.bind(Some(account(1))).unwrap().unwrap();
    let obsolete = cache.begin_online_check(&lease, 101u64.into()).unwrap();
    // A slow speculative read may own this gate; registration must not wait for
    // any file, and its fresh check must invalidate the abandoned read attempt.
    let io = cache.io().unwrap();
    let worker = cache.clone();
    let worker_lease = lease.clone();
    let (sent, result) = mpsc::channel();
    let handle = thread::spawn(move || {
        sent.send(worker.admit_source_for_write(&worker_lease, 101u64.into(), || true))
            .unwrap();
    });
    let admitted = result.recv_timeout(Duration::from_secs(1));
    drop(io);
    handle.join().unwrap();
    admitted
        .expect("current source registration must not wait for disk lookup")
        .unwrap();
    assert_eq!(
        cache.0.authority.prepare_online(obsolete).err(),
        Some(CacheError::Cancelled)
    );
    let mut request = cache.begin(&lease, 101u64).unwrap();
    cache.retain_write(&mut request, || true).unwrap();
    cache.start_write(&request).unwrap();
    cache.check_request(&request).unwrap();
    assert_eq!(cache.stats().unwrap(), Stats::default());
}

#[test]
fn source_admission_never_replaces_licensed_permission_or_revives_cancelled_source() {
    let f = Fixture::new();
    f.permission.hold_next.store(true, Ordering::Release);
    assert_eq!(
        f.cache
            .admit_source_for_write(&f.lease, 101u64.into(), || true),
        Err(CacheError::NoGrant)
    );
    assert!(
        f.entered.try_recv().is_err(),
        "a licensed permission lookup must not run here"
    );

    let directory = Sandbox::create(&std::env::temp_dir()).unwrap();
    let cache = AudioCache::open(
        directory.path.join("audio"),
        Arc::new(OnlineStreamAuthority::with_storage_permission(Arc::new(
            PrivateHttpCachePolicy,
        ))),
        CachePolicy::default(),
    )
    .unwrap();
    let lease = cache.bind(Some(account(1))).unwrap().unwrap();
    assert_eq!(
        cache.admit_source_for_write(&lease, 101u64.into(), || false),
        Err(CacheError::Cancelled)
    );
    assert!(matches!(
        cache.begin(&lease, 101u64),
        Err(CacheError::NoGrant)
    ));
    // Cancellation at either the preparation or commit checkpoint cannot leave
    // a usable admission, even if the initial current-source check passed.
    for allowed_checks in [1, 2] {
        let checks = AtomicU64::new(0);
        assert_eq!(
            cache.admit_source_for_write(&lease, 101u64.into(), || checks
                .fetch_add(1, Ordering::AcqRel)
                < allowed_checks),
            Err(CacheError::Cancelled)
        );
        assert!(matches!(
            cache.begin(&lease, 101u64),
            Err(CacheError::NoGrant)
        ));
    }
    cache.bind(None).unwrap();
    assert_eq!(
        cache.admit_source_for_write(&lease, 101u64.into(), || true),
        Err(CacheError::Cancelled)
    );
    assert_eq!(cache.stats().unwrap(), Stats::default());
}
